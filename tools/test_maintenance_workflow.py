"""Maintainer decisions must preserve conditions and the origin of evidence."""
import unittest
from test_closure_review import issue, comment, pr, CASES
from closure_review import review_issue
from evidence_context import evidence_source, result_context, generated_analysis


class MaintenanceWorkflowTests(unittest.TestCase):
    def test_table_footnote_retains_original_timeout_failure(self):
        c=comment('');c['body']='I re-checked on BMG, torch 2.15, same command.\n| Test | Result |\n| --- | --- |\n| test_ops.py::TestOps::test_one | passed in 797 s ³ |\n| test_ops.py::TestOps::test_two | passed |\n\n³ test_one passes, but with --timeout 600 from the issue, pytest-timeout aborts it.'
        result=review_issue(issue(CASES,[c],'[BMG] UT failures'),[])
        self.assertEqual(result['counts']['conditional'],1)
        self.assertEqual(result['counts']['passed'],1)
        self.assertEqual(result['disposed'],1)
        self.assertTrue(result['candidate'])
        self.assertNotEqual(result['status'],'优先审查关闭')
        self.assertIn('600',result['cases'][0]['condition_note'])
        self.assertNotIn('600',result['cases'][1].get('condition_note',''))

    def test_collection_workaround_is_not_unqualified_pass_or_future_plan(self):
        c=comment('');c['body']='| Test | Result |\n| --- | --- |\n| test_ops.py::TestOps::test_one | passed ⁴ |\n| test_ops.py::TestOps::test_two | passed ⁴ |\n\n⁴ The file fails to collect. These cases pass once that collection error is worked around.'
        result=review_issue(issue(CASES,[c]),[])
        self.assertEqual(result['counts']['workaround'],2)
        self.assertEqual(result['disposed'],0)
        self.assertTrue(result['candidate'])
        self.assertTrue(all('collection error' in c['evidence'][-1]['excerpt'] for c in result['cases']))
        planned=review_issue(issue(CASES,[comment('test_one will pass once the collection error is worked around.')]),[])
        self.assertEqual(planned['counts']['workaround'],0)

    def test_later_original_condition_retest_replaces_restricted_result(self):
        old=comment('test_one passed after increasing timeout to 900','20')
        fresh=comment('test_one passed. Verified in the original configuration.','28')
        result=review_issue(issue(CASES,[old,fresh]),[])
        self.assertEqual(result['cases'][0]['status'],'passed')
        self.assertEqual(result['cases'][0]['condition_note'],'')

    def test_generated_analysis_from_user_is_not_duplicate_confirmation(self):
        text='<details><summary>label-issue: #1</summary>\nDuplicate of #2.\n</details>\nGenerated by label job.'
        targets={'intel/torch-xpu-ops#2':{'type':'Issue','state':'OPEN'}}
        result=review_issue(issue(CASES,[comment(text)]),[],targets)
        self.assertFalse(result['candidate'])
        self.assertEqual(len(result['analysis_suggestions']),1)
        self.assertEqual(result['analysis_suggestions'][0]['source'],'自动分析建议')
        self.assertEqual(evidence_source(text),'自动分析建议')

    def test_generated_result_table_does_not_invent_inventory(self):
        c=comment('');c['body']='Generated by label job.\n| Test | Result |\n| --- | --- |\n| test_ops.py::TestOps::test_one | passed |'
        result=review_issue(issue('No test list.',[c]),[])
        self.assertEqual(result['total'],0)
        self.assertFalse(result['candidate'])

    def test_result_table_retains_equivalent_module_path_as_search_alias(self):
        c=comment('');c['body']='| Test | Result |\n| --- | --- |\n| test_ops.py::TestOps::test_one | passed |'
        result=review_issue(issue(CASES,[c]),[])
        self.assertIn('test_ops.py::TestOps::test_one',result['cases'][0]['aliases'])
        self.assertEqual(result['total'],2)

    def test_human_retest_requires_environment_revision_and_command_not_workflow(self):
        c=comment('I re-checked test_one test_two: passed on BMG Linux; torch==2.15.0, pytest with --timeout 600.')
        result=review_issue(issue(CASES,[c],'[BMG][Linux] UT failures'),[])
        self.assertEqual(result['configuration']['status'],'已匹配公开配置字段')
        self.assertEqual(result['status'],'优先审查关闭')
        self.assertNotIn('原报告 workflow 未确认',result['configuration']['checks'])
        missing=review_issue(issue(CASES,[comment('test_one test_two passed on BMG Linux.')],'[BMG][Linux] UT failures'),[])
        self.assertIn('人工复测未注明 PyTorch / torch-xpu-ops 版本或 commit',missing['configuration']['checks'])
        self.assertIn('人工复测未确认原复现命令与超时条件',missing['configuration']['checks'])

    def test_build_issue_uses_build_parameters_and_result_not_case_inventory(self):
        result=review_issue(issue('Build executed with USE_ONEMKL_XPU=OFF fails.',title='[dpclang] build fails'),[pr()])
        self.assertEqual(result['configuration']['kind'],'构建问题')
        self.assertTrue(any('USE_ONEMKL_XPU=OFF' in x for x in result['checks']))
        self.assertFalse(any('清单' in x or 'workflow 未确认' in x for x in result['checks']))
        self.assertNotEqual(result['status'],'优先审查关闭')

    def test_explicit_human_conclusion_does_not_claim_repository_role(self):
        self.assertEqual(evidence_source('I confirm this issue can be closed.'),'人工明确结论')
        self.assertEqual(evidence_source('I re-checked all tests on main.'),'人工复测记录')
        self.assertFalse(generated_analysis('Generated by the nightly testing job.'))

    def test_markdown_numbered_footnotes_are_attached_only_to_referencing_row(self):
        markdown='[^slow]: Original timeout aborts; passed after increasing timeout.'
        self.assertIn('increasing',result_context('| test_one | passed [^slow] |',markdown))
        self.assertNotIn('increasing',result_context('| test_two | passed |',markdown))


if __name__=='__main__':unittest.main()
