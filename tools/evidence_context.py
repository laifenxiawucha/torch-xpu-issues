"""Plain-text provenance and conservative environment matching for test evidence."""
import re


def generated_analysis(text):
    """Detect explicit job attribution, even when posted by a User account."""
    return bool(re.search(r'(?is)generated by.{0,140}(?:label|triage|repro|agent)|<summary>\s*label-issue:|trace mode:\s*evidence-only|labels\.md written', text))


def evidence_source(text, bot=False):
    if generated_analysis(text):
        return '自动分析建议'
    if bot:
        return 'Bot 评论'
    if re.search(r'(?i)\b(?:I|we)\s+(?:re-?checked|retested|verified|tested|reproduced)\b', text):
        return '人工复测记录'
    if re.search(r'(?i)\b(?:I confirm|confirmed duplicate|closing as duplicate|this issue can be closed)\b', text):
        return '人工明确结论'
    return '人工评论'


def result_context(line, markdown):
    """Attach table footnotes to their own rows, not neighboring cases."""
    if not line.lstrip().startswith('|'):
        return line
    markers = set(re.findall(r'[¹²³⁴⁵⁶⁷⁸⁹⁰]|\[\^[\w-]+\]', line))
    notes = []
    for marker in markers:
        definition = marker if len(marker) == 1 else marker + ':'
        match = re.search(r'(?m)^\s*' + re.escape(definition) + r'\s*(.*)$', markdown)
        if match:
            notes.append(definition + ' ' + match.group(1))
    return line + ('\n' + '\n'.join(sorted(notes)) if notes else '')


def pass_conditions(text):
    if re.search(r'(?i)work(?:ed|ing)? around|workaround|once.{0,100}collection error|collection error.{0,100}(?:worked around|bypass)|绕过', text):
        return 'workaround', '绕过收集或其他错误后通过；原命令仍需核对'
    if re.search(r'(?i)(?:original|issue.s|from the issue).{0,100}(?:timeout|abort)|--timeout\s+\d+.{0,100}(?:abort|timeout|times? out)|(?:increas|chang|rais|extend)\w*.{0,40}timeout|passes? (?:only )?in isolation|调整.{0,20}(?:超时|条件)', text):
        timeout = re.search(r'--timeout\s+(\d+)', text)
        note = '原 --timeout ' + timeout.group(1) + ' 条件仍会中止；需确认超时调整或后续修复' if timeout and re.search(r'(?i)abort|times? out', text) else '调整运行条件后通过；需确认原命令、超时条件及后续处理'
        return 'conditional', note
    return 'passed', ''


def review_kind(issue, cases):
    text = issue['title'] + '\n' + (issue.get('body') or issue.get('bodyText', ''))[:1800]
    if re.search(r'(?i)build (?:fails?|failure)|build.{0,30}fails|cmake error|编译失败|构建失败', text):
        return '构建问题'
    return '测试问题' if cases else '一般问题'


def execution_refs(text):
    found = re.findall(r'github\.com/([\w.-]+/[\w.-]+)/actions/runs/(\d+)', text)
    found += re.findall(r'([\w.-]+/[\w.-]+)@run:(\d+)', text)
    return list(dict.fromkeys(f'{repo}@run:{number}' for repo, number in found))


def platforms(text):
    hardware = set(re.findall(r'\b(?:PVC|BMG|B60|B580|LNL|MTL|ARL|DG2|PTL(?:-H)?)\b', text, re.I))
    hardware = {('BMG' if h.upper() in ('B60', 'B580') else 'PTL' if h.upper() == 'PTL-H' else h.upper()) for h in hardware}
    operating = set()
    if re.search(r'\bWSL\w*\b', text, re.I):
        operating.add('WSL')
    if re.search(r'\bWindows\b', text, re.I):
        operating.add('Windows')
    if re.search(r'\b(?:Linux|Ubuntu|Debian|CentOS)\b', text, re.I):
        operating.add('Linux')
    return {'hardware': sorted(hardware), 'os': sorted(operating)}


def evidence_scope(text, runs):
    scope = platforms(text)
    scope['runs'] = execution_refs(text)
    scope['versions'] = list(dict.fromkeys(re.findall(r'(?i)(?:torch\s*[=:]+\s*|PyTorch(?: version)?\s*[:=]\s*|release/)(2\.\d+(?:\.\d+)?[^\s`<>,;]*)', text)))
    scope['same_configuration'] = bool(re.search(r'(?i)(?:verified|retested|passed).{0,80}(?:same|original) (?:configuration|environment)|(?:same|original) (?:configuration|environment).{0,80}(?:verified|passed)', text))
    scope['revision_recorded'] = bool(scope['versions'] or re.search(r'(?i)\b[0-9a-f]{7,40}\b', text))
    scope['command_recorded'] = bool(re.search(r'(?i)pytest|--timeout|same (?:command|env)|env from the issue|原(?:命令|环境)', text))
    return scope


def configuration_check(issue, cases, runs):
    labels = [x['name'] for x in issue.get('labels', {}).get('nodes', [])]
    expected = platforms(issue['title'] + ' ' + ' '.join(labels))
    original = [runs.get(ref, {}) for ref in execution_refs(issue.get('body') or issue.get('bodyText', ''))]
    paths = {r.get('path') for r in original if r.get('available') and r.get('path')}
    branches = {r.get('branch') for r in original if r.get('available') and r.get('branch')}
    if re.search(r'(?i)dpclang', issue['title'] + ' ' + (issue.get('body') or '')[:1800]):
        paths.add('.github/workflows/pull_dpclang.yml')
    release = re.search(r'(?i)release[/ ](\d+\.\d+)', issue['title'])
    checks = []
    checked = 0
    kind = review_kind(issue, cases)
    methods = set()
    if kind == '构建问题':
        parameters = list(dict.fromkeys(re.findall(r'\b[A-Z][A-Z0-9_]+=(?:OFF|ON|0|1)\b', issue.get('body') or issue.get('bodyText', ''))))
        checks.extend(['核对原构建参数' + ('（' + '、'.join(parameters) + '）' if parameters else '') + '及编译器版本',
                       '提供修复合并后、目标分支及依赖 pin 下的构建结果', '确认原编译错误消失，并核对受影响的构建组合'])
        return {'kind': kind, 'methods': ['构建命令与结果核对'], 'status': '构建结果待核对', 'checks': checks, 'expected': expected, 'original_runs': original}
    for case in cases:
        if case['status'] not in ('passed', 'conditional', 'workaround'):
            continue
        checked += 1
        notes = []
        scope = case['evidence'][-1].get('configuration', {}) if case['evidence'] else {}
        actual_runs = [runs.get(ref,{}) for ref in scope.get('runs', []) if runs.get(ref,{}).get('available')]
        automated = bool(case['evidence'] and case['evidence'][-1]['source'] == 'Bot 评论')
        methods.add('CI 运行配置核对' if automated else '人工复测环境与命令核对')
        if not scope.get('same_configuration'):
            if automated and not paths:
                notes.append('原报告 workflow 未确认')
            elif automated and not actual_runs:
                notes.append('通过记录缺少可核对的 workflow run')
            elif automated and not paths.intersection(r.get('path') for r in actual_runs):
                notes.append('通过记录与原报告 workflow 不同')
            if automated and branches and actual_runs and not branches.intersection(r.get('branch') for r in actual_runs):
                notes.append('通过记录与原报告分支不同')
            if not automated and not scope.get('revision_recorded'):
                notes.append('人工复测未注明 PyTorch / torch-xpu-ops 版本或 commit')
            if not automated and not scope.get('command_recorded'):
                notes.append('人工复测未确认原复现命令与超时条件')
            if expected['hardware'] and not set(expected['hardware']).issubset(scope.get('hardware', [])):
                notes.append('通过记录未覆盖原报告全部硬件')
            if expected['os'] and not set(expected['os']).issubset(scope.get('os', [])):
                notes.append('通过记录未覆盖原报告全部操作系统')
        if release and not any(v.startswith(release.group(1)) for v in scope.get('versions', [])):
            notes.append('通过记录未确认目标 release/' + release.group(1))
        if not notes and not expected['hardware'] and not expected['os'] and not scope.get('same_configuration'):
            notes.append('原报告平台范围需人工确认')
        if case['status'] in ('conditional', 'workaround'):
            notes.append(case.get('condition_note') or '受限通过，原条件及后续处理待确认')
        case['configuration_status'] = '待确认' if notes else '已匹配公开配置字段'
        case['configuration_notes'] = notes
        checks.extend(notes)
    if not cases:
        checks.append('核对原问题范围、复现步骤、修复覆盖及目标版本的验证结果')
    return {'kind': kind, 'methods': sorted(methods), 'status': '需要核对配置' if checks else '已匹配公开配置字段' if checked else '无通过记录，配置待核对' if cases else '覆盖未知',
            'checks': list(dict.fromkeys(checks)), 'expected': expected,
            'original_runs': original}
